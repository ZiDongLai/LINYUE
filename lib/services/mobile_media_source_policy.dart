import 'dart:convert';
import 'dart:io';
import 'package:crypto/crypto.dart';
import 'dart:math' as math;

/// Owns only app-private, durable copies of images/videos picked on Android.
/// The sending queue and original-preview history can rely on them even after
/// the Android picker/cache is reclaimed. Never deletes a user-selected file.
final class MobileMediaSourcePolicy {
  MobileMediaSourcePolicy._();

  static const int maximumBytes = 1024 * 1024 * 1024;
  static const String receiptDirectoryName = 'LinYueMediaStageReceiptsV1';

  /// Stable, non-path receipt identifier: no user filename is used as a path.
  static String receiptFileName(String stagedBaseName) =>
      '${sha256.convert(utf8.encode(stagedBaseName))}.json';

  static File receiptFor(File staged, Directory root) => File(
      '${root.path}${Platform.pathSeparator}'
      '${receiptFileName(staged.uri.pathSegments.last)}');

  /// Used ONLY when a newly staged batch fails before entering the queue.
  /// This must never be exposed as general user-data cleanup.
  static Future<void> discardUnqueuedStage({
    required File staged,
    required Directory receiptDirectory,
  }) async {
    final receipt = receiptFor(staged, receiptDirectory);
    if (await staged.exists()) await staged.delete();
    if (await receipt.exists()) await receipt.delete();
  }
  static const Set<String> imageExtensions = {
    '.jpg', '.jpeg', '.png', '.gif', '.webp', '.heic', '.heif', '.bmp',
  };

  static const Set<String> videoExtensions = {
    '.mp4', '.m4v', '.mov', '.3gp', '.3g2', '.webm', '.mkv',
    '.avi', '.wmv', '.mpg', '.mpeg',
  };

  static bool isVideoName(String fileName) {
    final lower = fileName.toLowerCase();
    return videoExtensions.any(lower.endsWith);
  }

  static bool isSupportedMediaName(String name) =>
      isImageName(name) || isVideoName(name);

  static bool isImageName(String fileName) {
    final lower = fileName.toLowerCase();
    return imageExtensions.any(lower.endsWith);
  }

  static String safeName(String name) {
    final leaf = name.replaceAll('\\', '/').split('/').last;
    final cleaned = leaf.replaceAll(RegExp(r'[\\/:*?"<>|\x00-\x1f]'), '_').trim();
    return cleaned.isEmpty || cleaned == '.' || cleaned == '..'
        ? 'media_file' : cleaned;
  }

  static Future<File> stageFile({
    required File source,
    required Directory stagingRoot,
    required String displayName,
    Directory? receiptDirectory,
    int maximumFileBytes = maximumBytes,
  }) async {
    if (!isSupportedMediaName(displayName)) {
      throw const FormatException('所选文件不是支持的图片或视频格式');
    }
    if (!await source.exists()) {
      throw StateError('所选媒体文件已不存在，请重新选择');
    }
    final length = await source.length();
    if (length <= 0 || length > maximumFileBytes) {
      throw StateError('文件大小为零或超过当前 1 GiB 的传输限制');
    }
    await stagingRoot.create(recursive: true);
    final unique = '${DateTime.now().microsecondsSinceEpoch}_'
        '${math.Random.secure().nextInt(0x7fffffff)}';
    final destination = File('${stagingRoot.path}${Platform.pathSeparator}'
        '${unique}_${safeName(displayName)}');
    var bytesWritten = 0;
    File? tempReceipt;
    File? committedReceipt;
    try {
      final sink = destination.openWrite();
      try {
        await for (final chunk in source.openRead()) {
          bytesWritten += chunk.length;
          if (bytesWritten > maximumFileBytes) {
            throw StateError('文件在读取过程中超过大小限制');
          }
          sink.add(chunk);
        }
        await sink.flush();
      } finally {
        await sink.close();
      }
      if (bytesWritten != length) {
        throw StateError('媒体文件读取时内容发生变化，请重新选择');
      }
      if (receiptDirectory != null) {
        // Register only copies generated by LINYUE from this version onward.
        // A receipt documents provenance; it does NOT authorize deletion.
        await receiptDirectory.create(recursive: true);
        final receipt = receiptFor(destination, receiptDirectory);
        if (await receipt.exists()) {
          throw StateError('媒体来源登记已存在，已中止本次添加');
        }
        final tmp = File('${receipt.path}.tmp_${math.Random.secure().nextInt(0x7fffffff)}');
        tempReceipt = tmp;
        await tmp.writeAsString(jsonEncode({
          'schema': 1,
          'producer': 'linyue-mobile-stage',
          'storedName': destination.uri.pathSegments.last,
          'bytes': bytesWritten,
          'createdAtUtc': DateTime.now().toUtc().toIso8601String(),
        }), flush: true);
        await tmp.rename(receipt.path);
        tempReceipt = null;
        committedReceipt = receipt;
      }
      return destination;
    } catch (_) {
      if (tempReceipt != null && await tempReceipt.exists()) {
        await tempReceipt.delete();
      }
      if (committedReceipt != null && await committedReceipt.exists()) {
        await committedReceipt.delete();
      }
      if (await destination.exists()) await destination.delete();
      rethrow;
    }
  }
}
